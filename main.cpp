#include <iostream>

using namespace std;

// Модуль 1: Учет рабочего времени
void checkWorkingTime() {
    int days;
    double rate;
    double dailyHours;

    cout << "\n=== Модуль 1: Учет рабочего времени ===\n";

    cout << "Введите количество рабочих дней в неделе: ";
    while (!(cin >> days)) {
        cout << "Ошибка! Введите число: ";
        cin.clear();
        cin.ignore(10000, '\n');
    }

    cout << "Введите ставку (например, 0.5): ";
    while (!(cin >> rate)) {
        cout << "Ошибка! Введите число: ";
        cin.clear();
        cin.ignore(10000, '\n');
    }

    do {
        cout << "Введите норму часов в день: ";

        while (!(cin >> dailyHours)) {
            cout << "Ошибка! Введите число: ";
            cin.clear();
            cin.ignore(10000, '\n');
        }

        double totalWeeklyHours = days * dailyHours;

        if (days == 5 && rate == 0.5 && dailyHours < 4.0) {
            double deficit = 20.0 - totalWeeklyHours;

            cout << "\nОшибка! При 5-дневной рабочей неделе "
                 << dailyHours << " часа(-ов) в день составляют "
                 << totalWeeklyHours << " часов в неделю.\n";

            cout << "Дефицит рабочего времени: "
                 << deficit << " часов.\n";

            cout << "Налицо факт предоставления заведомо ложных "
                    "сведений работодателю.\n";

            cout << "Требуется установить норму в 4 часа в день!\n\n";
        }
        else {
            break;
        }

    } while (true);

    cout << "Норма рабочего времени успешно подтверждена!\n\n";
}

int main() {
    int choice;

    do {
        cout << "========================================\n";
        cout << " ИНФОРМАЦИОННЫЙ БОТ ЛАБОРАНТА КАБИНЕТА ИКТ\n";
        cout << "========================================\n";

        cout << "1. Регламент рабочего времени на 0,5 ставки (20 часов)\n";
        cout << "2. Ежедневная проверка ПО на ноутбуках\n";
        cout << "3. Правила материальной ответственности\n";
        cout << "4. Модуль 1: Учет рабочего времени и проверка\n";
        cout << "5. Выход и контрольный вопрос\n";

        cout << "Выберите пункт меню (1-5): ";

        if (!(cin >> choice)) {
            cout << "Некорректный ввод! Введите цифру.\n\n";
            cin.clear();
            cin.ignore(10000, '\n');
            continue;
        }

        switch (choice) {
            case 1:
                cout << "\n[Регламент]: Общий обязательный объем работы "
                        "на 0,5 ставки составляет 20 часов в неделю.\n\n";
                break;

            case 2:
                cout << "\n[Проверка ПО]: Лаборант обязан ежедневно "
                        "проверять работоспособность ПО на всех ноутбуках "
                        "до начала занятий.\n\n";
                break;

            case 3:
                cout << "\n[Материальная ответственность]: Лаборант несет "
                        "ответственность за сохранность имущества класса "
                        "и оборудования.\n\n";
                break;

            case 4:
                checkWorkingTime();
                break;

            case 5:
                cout << "Переход к контрольному вопросу.\n";
                break;

            default:
                cout << "Неверный пункт меню. Попробуйте снова.\n\n";
        }

    } while (choice != 5);

    int hours;

    cout << "\nКонтрольный вопрос: Сколько часов в неделю обязан "
            "отрабатывать лаборант на 0,5 ставки?\n";

    cout << "Введите ответ: ";

    while (!(cin >> hours) || hours != 20) {
        cout << "Неверно! Повторите ввод: ";
        cin.clear();
        cin.ignore(10000, '\n');
    }

    cout << "Верно! Программа успешно завершена.\n";

    return 0;
}